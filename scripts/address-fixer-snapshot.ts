/**
 * Regenerates the bundled street snapshot used by the address fixer at
 * runtime: data.gov.il -> lib/address-fixer/data/streets-snapshot.ts
 *
 * Run manually after the street list changes:
 *   npx tsx scripts/address-fixer-snapshot.ts
 */

import { gzipSync } from "node:zlib"
import { writeFileSync, mkdirSync } from "node:fs"
import { join } from "node:path"
import { fetchStreetRowsFromGov, type StreetRow } from "../lib/address-fixer/sync"

interface SnapshotPayload {
  version: string
  count: number
  cities: Array<[number, string, Array<[number, string]>]>
}

function buildPayload(rows: StreetRow[]): SnapshotPayload {
  const byCity = new Map<number, { name: string; streets: Array<[number, string]> }>()
  for (const row of rows) {
    let city = byCity.get(row.city_code)
    if (!city) {
      city = { name: row.city_name, streets: [] }
      byCity.set(row.city_code, city)
    }
    city.streets.push([row.street_code, row.street_name])
  }
  return {
    version: new Date().toISOString().slice(0, 10),
    count: rows.length,
    cities: [...byCity.entries()].map(([code, city]) => [code, city.name, city.streets]),
  }
}

async function main() {
  console.log("Fetching street list from data.gov.il ...")
  const rows = await fetchStreetRowsFromGov()
  console.log(`Fetched ${rows.length} rows.`)

  const payload = buildPayload(rows)
  const json = JSON.stringify(payload)
  const encoded = gzipSync(Buffer.from(json, "utf8"), { level: 9 }).toString("base64")

  const dir = join(process.cwd(), "lib", "address-fixer", "data")
  mkdirSync(dir, { recursive: true })
  const file = join(dir, "streets-snapshot.ts")
  writeFileSync(
    file,
    `/**\n * Generated by scripts/address-fixer-snapshot.ts — do not edit by hand.\n *\n * Source: data.gov.il resource 9ad3862c-8391-4b2f-84a4-2d4c68625f4b\n * Snapshot: ${payload.version} (${payload.count} streets, ${payload.cities.length} cities)\n */\n\nexport const STREETS_SNAPSHOT_VERSION = "${payload.version}"\nexport const STREETS_SNAPSHOT_COUNT = ${payload.count}\nexport const STREETS_SNAPSHOT_GZIP_BASE64 =\n  "${encoded}"\n`,
    "utf8"
  )

  console.log(
    `Wrote ${file} (${(encoded.length / 1024 / 1024).toFixed(2)} MB base64, ${payload.cities.length} cities).`
  )
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
